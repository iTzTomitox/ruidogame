// Minúsculas acentuadas: tilde en la fila 0, base desde la fila 2.
const ACCENTS = { 'á': ['a', '..#.'], 'é': ['e', '..#.'], 'ó': ['o', '..#.'], 'ú': ['u', '..#.'], 'ü': ['u', '#..#'] };
for (const [ch, [base, mark]] of Object.entries(ACCENTS)) G[ch] = [0, mark, '....', ...G[base].slice(1)];
G['ñ'] = [0, '.#.#', '#.#.', ...G.n.slice(1)];
G['í'] = [0, '.#', '..', '#.', '#.', '#.', '#.', '#.'];

// Caracteres sin glifo propio.
const FALLBACK = { 'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'Ñ': 'N', 'Ü': 'U', '“': '"', '”': '"', '‘': "'", '’': "'", '—': '-', '–': '-', '…': '...', ' ': ' ' };

const ROWS = 9;
export const LINE_HEIGHT = 10;

export function normalize(str) {
  let out = '';
  for (const ch of String(str ?? '')) {
    if (ch === '\n' || G[ch]) out += ch;
    else out += FALLBACK[ch] ?? '?';
  }
  return out;
}

const width = (ch) => Math.max(...G[ch].slice(1).map((r) => r.length));
const advance = (ch) => width(ch) + 1;

export function measure(str) {
  let w = 0;
  for (const ch of normalize(str)) w += advance(ch);
  return Math.max(0, w - 1);
}

export function wrap(str, maxWidth) {
  return normalize(str)
    .split('\n')
    .map((para) => {
      const lines = [];
      let line = '';
      for (const word of para.split(' ')) {
        const next = line ? `${line} ${word}` : word;
        if (line && measure(next) > maxWidth) {
          lines.push(line);
          line = word;
        } else line = next;
      }
      lines.push(line);
      return lines.join('\n');
    })
    .join('\n');
}

export function registerPixelFont(scene, key = 'pixel') {
  const chars = Object.keys(G);
  const texW = chars.reduce((s, ch) => s + width(ch) + 1, 0);
  const tex = scene.textures.createCanvas(key, texW, ROWS);
  const ctx = tex.getContext();
  ctx.fillStyle = '#ffffff';
  const data = { font: key, size: ROWS, lineHeight: LINE_HEIGHT, chars: {} };
  let x = 0;
  for (const ch of chars) {
    const [top, ...rows] = G[ch];
    const w = width(ch);
    rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') ctx.fillRect(x + rx, top + ry, 1, 1);
    });
    data.chars[ch.charCodeAt(0)] = {
      x, y: 0, width: w, height: ROWS,
      centerX: w >> 1, centerY: ROWS >> 1,
      xOffset: 0, yOffset: 0, xAdvance: advance(ch),
      data: {}, kerning: {},
      u0: x / texW, v0: 0, u1: (x + w) / texW, v1: 1,
    };
    x += w + 1;
  }
  tex.refresh();
  scene.cache.bitmapFont.add(key, { data, texture: key, frame: null });
}
